#!/usr/bin/env python3
"""Write ~/.config/hypr/colors.lua with window-border colors that contrast
with a wallpaper.

The wallpaper's dominant hue is found by averaging hues around the colour
wheel, weighted by how saturated and bright each pixel is (so grey sky and
black shadows don't count). The active border is a gradient through the
complementary hue (opposite side of the wheel) and its neighbour, kept
bright and saturated so it stands out against the blurred wallpaper.

usage: border-colors.py <image> [output.lua]
"""

import colorsys
import math
import os
import sys

from PIL import Image

FALLBACK_HUE = 207  # soft blue, used for near-greyscale wallpapers


def dominant_hue(path):
    with Image.open(path) as im:
        im = im.convert("RGB")
        im.thumbnail((96, 96))
        raw = im.tobytes()
    pixels = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]

    x = y = total = 0.0
    for r, g, b in pixels:
        h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        w = s * v
        if w < 0.05:
            continue
        x += math.cos(h * 2 * math.pi) * w
        y += math.sin(h * 2 * math.pi) * w
        total += w

    # strength: how much colour there is and how much it agrees on one hue
    strength = math.hypot(x, y) / max(len(pixels), 1)
    if total == 0 or strength < 0.02:
        return None
    return math.degrees(math.atan2(y, x)) % 360


def hsl_hex(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, l, s)
    return "%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    image = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser("~/.config/hypr/colors.lua")

    hue = dominant_hue(image)
    border = FALLBACK_HUE if hue is None else (hue + 180) % 360

    start = hsl_hex(border, 0.85, 0.66)
    end = hsl_hex(border + 40, 0.80, 0.72)
    inactive = hsl_hex(border, 0.15, 0.35)

    lua = f"""-- Generated by scripts/border-colors.py from {image}
-- wallpaper hue: {'none' if hue is None else round(hue)}, border hue: {round(border)} (complement)
-- Do not edit: wallpaper.sh rewrites this file.
hl.config({{
    general = {{
        col = {{
            active_border   = {{ colors = {{ "rgba({start}ff)", "rgba({end}ff)" }}, angle = 45 }},
            inactive_border = "rgba({inactive}aa)",
        }},
    }},
}})
"""
    with open(out, "w") as f:
        f.write(lua)
    print(f"wallpaper hue {hue!s:.5} -> border #{start} / #{end}")


if __name__ == "__main__":
    main()
